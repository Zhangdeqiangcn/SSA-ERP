-- 0116 采购申请表头「期望日期」改为「申请日期」（V3.102.0）
-- ───────────────────────────────────────────────────────────────────────────
-- 背景（强哥诉求）：采购申请表头的「期望日期」是手填框，容易空置/误填；
--   期望交货语义自 V3.98.0 起已由明细行「期望交货时间」（delivery_date）
--   接管，表头该字段已边缘化。强哥要求把表头该字段改为「申请日期」，
--   直接拉取提交当时的时间（自动生成、用户不可填）。
-- 设计：
--   · application_date：申请日期（yyyy-mm-dd，本地时区）。提交/暂存时
--     由前端实时取当天写入；编辑旧单回填历史值，无历史值时兜底 created_at
--     的日期部分（申请日期本质=创建日期）。
--   · expected_date 列保留不动：历史单据存的是「期望到货日期」语义，
--     下游（采购订单转单期望交货、询价 requiredDate、打印模板）仍在用；
--     新建单据不再写表头期望日期（期望交货看明细行 delivery_date）。
--   · 幂等：ADD COLUMN 无 IF NOT EXISTS（SQLite 不支持），靠 d1_migrations
--     登记表保证只执行一次；重复执行会报 duplicate column，属预期。
-- ═══════════════════════════════════════════════════════════════════════════
ALTER TABLE purchase_requests ADD COLUMN application_date TEXT;
